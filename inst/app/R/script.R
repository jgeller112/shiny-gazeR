# R script export: writes the current run as a standalone R script that
# reproduces it with gazeR. The pre-processing steps are written out as
# gazeR calls (only the branches the settings use); file reading, sampling
# rates and behavioural rules use the app's own helpers, copied verbatim from
# pipeline.R so the script and the app can't drift apart.

# Source of the helpers: pipeline.R next to this file (the app directory is
# the working directory while the app runs), else the installed copy
pipeline_source <- function() {
  f <- file.path("R", "pipeline.R")
  if (file.exists(f)) f else system.file("app", "R", "pipeline.R", package = "shinygazer")
}

# One R literal per value, e.g. c("a", "b"), -100, NA
lit <- function(x) {
  if (is.null(x)) return("NULL")
  if (is.character(x) && !length(x)) return("character()")
  deparse1(unname(x), collapse = "", width.cutoff = 500L)
}

# Source text (with the comment block above it) of the named top-level
# functions in pipeline.R, plus every pipeline.R function they call
script_helpers <- function(fns, file = pipeline_source()) {
  lines <- readLines(file, warn = FALSE)
  exprs <- parse(text = lines, keep.source = TRUE)
  refs <- attr(exprs, "srcref")
  is_fn <- vapply(exprs, function(e) is.call(e) && identical(e[[1]], as.name("<-")) &&
                    is.call(e[[3]]) && identical(e[[3]][[1]], as.name("function")), logical(1))
  defs <- stats::setNames(which(is_fn), vapply(exprs[is_fn], function(e) as.character(e[[2]]), ""))
  need <- character()
  todo <- intersect(fns, names(defs))
  while (length(todo)) {
    need <- union(need, todo)
    called <- unlist(lapply(todo, function(f) all.names(exprs[[defs[[f]]]][[3]])))
    todo <- setdiff(intersect(called, names(defs)), need)
  }
  need <- names(defs)[names(defs) %in% need]  # file order
  vapply(need, function(f) {
    i <- defs[[f]]
    first <- refs[[i]][1]
    start <- first
    while (start > 1 && grepl("^#", lines[start - 1])) start <- start - 1
    paste(lines[start:refs[[i]][3]], collapse = "\n")
  }, character(1))
}

# The script. `p` is the run's parameters; `meta` holds what the pipeline
# doesn't know: tracker, file names, reader options, column mapping,
# behavioural file, eyes (TRUE for Eye = Both), has_message, versions.
pipeline_script <- function(p, meta) {
  out <- character()
  add <- function(...) out <<- c(out, paste0(...))
  body <- character()
  b <- function(...) body <<- c(body, paste0(...))
  has <- function(x) !is.null(x) && length(x) == 1 && !is.na(x) && nzchar(x)
  num <- function(x) !is.null(x) && length(x) == 1 && is.finite(x)
  fns <- c("standardise_columns", "apply_sampling_rates")

  # ---- Header ----
  add("# Pupil pre-processing with gazeR")
  add("# Generated by shiny gazeR ", meta$app_version, " (gazeR ", meta$gazer_version, ") on ",
      format(Sys.Date()), ".")
  add("# Re-runs the app's pre-processing with the same settings and gives the same")
  add("# processed samples, binned data and trial exclusions.")
  add("#")
  add("# Needs gazeR >= ", meta$gazer_version, ":")
  add("# install.packages(\"gazer\", repos = c(\"https://jgeller112.r-universe.dev\", \"https://cloud.r-project.org\"))")
  add("")
  add("library(dplyr)")
  add("")

  # ---- Load ----
  load <- character()
  l <- function(...) load <<- c(load, paste0(...))
  l("# ---- 1. Load data -------------------------------------------------------")
  l("")
  starts <- function(x) {
    s <- trimws(unlist(strsplit(if (is.null(x)) "" else x, ",")))
    s <- s[nzchar(s)]
    if (length(s)) lit(s) else "NULL"
  }
  if (isTRUE(meta$example)) {
    l("# The example data shipped with gazeR")
    l("files <- system.file(\"extdata\", \"pupil_sample_files_edf.xls.gz\", package = \"gazer\")")
  } else {
    l("data_dir <- \"path/to/your/data\"  # the folder with the files below")
    l("files <- file.path(data_dir, ", lit(meta$files), ")")
  }
  eye <- if (is.null(meta$asc_eye)) "average" else meta$asc_eye
  switch(meta$tracker,
    tobii = {
      fns <- c(fns, "read_tobii_upload")
      l("msg_files <- file.path(data_dir, ", lit(meta$msg_files), ")")
      l("raw <- read_tobii_upload(files, basename(files), msg_files, basename(msg_files), eye = ", lit(eye),
        ", onset_prefix = ", lit(meta$tobii_onset), ", offset_prefix = ", lit(meta$tobii_offset), ")")
    },
    pupillabs = {
      fns <- c(fns, "read_pupillabs_upload")
      l("raw <- read_pupillabs_upload(files, basename(files), subject = ", lit(meta$pl_subject),
        ", start_mode = ", lit(meta$pl_start_mode),
        ", start_messages = ", if (identical(meta$pl_start_mode, "exact")) starts(meta$pl_start_messages) else "NULL",
        ", max_event_lag_ms = ", lit(meta$pl_lag), ", aoi = ", lit(isTRUE(meta$pl_aoi)), ")")
    },
    prolab = {
      fns <- c(fns, "read_prolab_upload")
      l("raw <- read_prolab_upload(files, basename(files), eye = ", lit(eye),
        ", trial_start = ", starts(meta$prolab_trial_start), ")")
    },
    bids = {
      fns <- c(fns, "read_bids_upload")
      l("raw <- read_bids_upload(files, basename(files), eye = ", lit(eye),
        ", trial_start = ", starts(meta$bids_trial_start), ")")
    },
    {
      fns <- c(fns, "read_gazer_files")
      l("raw <- read_gazer_files(files, basename(files), eye = ", lit(eye), ")")
    })
  l("")
  l("# Column mapping: rename to gazeR's column names")
  cols <- meta$cols[vapply(meta$cols, has, logical(1))]
  l("d <- standardise_columns(raw, list(",
    paste(sprintf("%s = %s", names(cols), vapply(cols, lit, "")), collapse = ", "), "))")
  if (has(meta$behav_file) && length(meta$behav_keys)) {
    fns <- c(fns, "join_behaviour")
    l("")
    l("# Behavioural data, one row per trial, joined onto the samples")
    l("behav <- tibble::as_tibble(data.table::fread(file.path(data_dir, ", lit(meta$behav_file),
      "), na.strings = c(\"NA\", \"\")))")
    l("d <- join_behaviour(d, behav, keys = ", lit(meta$behav_keys), ")")
  }
  l("")

  # ---- Pre-processing (body; a function per eye for Eye = Both) ----
  use_acc <- has(p$acc_col) && length(p$acc_correct)
  use_rt <- has(p$rt_col)
  if (use_acc || use_rt) {
    fns <- c(fns, "behaviour_exclusions")
    b("# Behavioural exclusions (accuracy, RT), before any processing")
    b("behav_excl <- behaviour_exclusions(d, list(",
      paste(c(if (use_acc) sprintf("acc_col = %s, acc_correct = %s", lit(p$acc_col), lit(p$acc_correct)),
              if (use_rt) sprintf("rt_col = %s, rt_min = %s, rt_max = %s, rt_sd = %s", lit(p$rt_col),
                                  lit(p$rt_min), lit(p$rt_max), lit(p$rt_sd))), collapse = ", "), "))")
    b("d <- anti_join(d, behav_excl, by = c(\"subject\", \"trial\"))")
    b("")
  }
  b("# Sampling rates (adds .hz, each participant's processing rate)")
  b("d <- apply_sampling_rates(d, list(hz_override = ", lit(p$hz_override), ", rate_mode = ", lit(p$rate_mode),
    ", resample = ", lit(isTRUE(p$resample)), ", target_rate = ", lit(p$target_rate), "))$data")
  b("")

  b("# ---- 2. Blinks and artifacts ----")
  b("d$pupil[!is.na(d$pupil) & d$pupil <= 0] <- NA")
  if (num(p$pupil_min)) b("d$pupil[!is.na(d$pupil) & d$pupil < ", lit(p$pupil_min), "] <- NA  # plausible range")
  if (num(p$pupil_max)) b("d$pupil[!is.na(d$pupil) & d$pupil > ", lit(p$pupil_max), "] <- NA")
  b("d$blink_detected <- 0L")
  if (isTRUE(p$use_blink_col)) {
    b("if (\"blink\" %in% names(d)) d$blink_detected <- as.integer(!is.na(d$blink) & d$blink == 1)  # tracker blinks")
  }
  if (identical(p$blink_method, "hershman")) {
    b("# Noise-based blink detection (Hershman et al., 2018)")
    b("d <- d %>%")
    b("  group_by(subject, trial) %>%")
    b("  mutate(blink_detected = pmax(blink_detected, as.integer(gazer::detect_blinks_noise(")
    b("    pupil, hz = .hz[1], smooth_ms = ", lit(p$hershman_smooth), ", gap_ms = ", lit(p$hershman_gap), ") > 0))) %>%")
    b("  ungroup()")
  }
  b("d$pupil[d$blink_detected == 1] <- NA")
  b("# Missing data for the exclusion threshold: before padding and speed outliers")
  b("missing_raw <- is.na(d$pupil)")
  b("")
  b("# Blink padding")
  b("d <- d %>%")
  b("  group_by(subject, trial) %>%")
  b("  mutate(extendpupil = gazer::extend_blinks(pupil, fillback = ", lit(p$fillback),
    ", fillforward = ", lit(p$fillforward), ", hz = .hz[1])) %>%")
  b("  ungroup()")
  if (isTRUE(p$use_mad)) {
    fns <- c(fns, "remove_speed_outliers")
    b("")
    b("# Dilation-speed outliers (Kret & Sjak-Shie, 2019)")
    b("d <- d %>%")
    b("  group_by(subject, trial) %>%")
    b("  mutate(extendpupil = remove_speed_outliers(extendpupil, time, n = ", lit(p$mad_n), ")) %>%")
    b("  ungroup()")
  }
  if (isTRUE(p$gaze_correct)) {
    b("")
    b("# Gaze-position correction (pupil foreshortening error), per participant")
    b("d <- gazer::correct_pupil_gaze(d, pupil_col = \"extendpupil\", x_col = \"x\", y_col = \"y\",")
    b("                               by = \"subject\", model = ", lit(p$gaze_model),
      ", reference = ", lit(gaze_reference(p)), ")")
    b("gaze_fit <- attr(d, \"gaze_fit\")  # samples used, R-squared and reference per participant")
    b("attr(d, \"gaze_fit\") <- NULL")
  }
  b("")

  b("# ---- Missing-data exclusions ----")
  use_window <- isTRUE(p$timelock) && isTRUE(meta$has_message)
  if (use_window) {
    fns <- c(fns, "event_onset")
    w <- c(if (num(p$window[1])) sprintf("tz >= %s", lit(p$window[1])),
           if (num(p$window[2])) sprintf("tz <= %s", lit(p$window[2])))
    b("# Measured inside the analysis window, relative to the time-lock event")
    b("tz <- d %>%")
    b("  group_by(subject, trial) %>%")
    b("  mutate(.tz = event_onset(time, message, ", lit(p$timelock_event), ")) %>%")
    b("  pull(.tz)")
    b(if (length(w)) paste0("in_window <- is.na(tz) | (", paste(w, collapse = " & "), ")")
      else "in_window <- rep(TRUE, length(tz))")
    b("has_ev <- !is.na(tz)")
  } else {
    b("in_window <- rep(TRUE, nrow(d))")
    b("has_ev <- rep(TRUE, nrow(d))")
  }
  b("quality <- d %>%")
  b("  mutate(.in = in_window, .ev = has_ev, .miss = missing_raw) %>%")
  b("  group_by(subject, trial) %>%")
  b("  summarise(samples = sum(.in), missing_n = sum(.miss[.in]), prop_missing = missing_n / samples,")
  b("            valid_total = sum(!is.na(extendpupil)), has_event = any(.ev), .groups = \"drop\") %>%")
  b("  group_by(subject) %>%")
  b("  # Participant level: missing samples pooled across their analysable trials")
  b("  mutate(subject_prop_missing = if (any(has_event)) sum(missing_n[has_event]) / sum(samples[has_event]) else NA_real_) %>%")
  b("  ungroup() %>%")
  b("  mutate(reason = case_when(")
  b("    !has_event ~ ", lit(paste0("no ", event_label(p$timelock_event), " event")), ",")
  b("    subject_prop_missing > ", lit(p$missingthresh), " ~ \"subject missing data\",")
  b("    valid_total < 2 ~ \"no valid samples\",")
  b("    prop_missing > ", lit(p$missingthresh), " ~ \"trial missing data\",")
  b("    TRUE ~ \"kept\"),")
  b("    excluded = reason != \"kept\") %>%")
  b("  select(-valid_total, -has_event, -missing_n)")
  b("d <- semi_join(d, filter(quality, !excluded), by = c(\"subject\", \"trial\"))")
  if (use_acc || use_rt) {
    b("quality <- bind_rows(quality, mutate(behav_excl, samples = NA_integer_, prop_missing = NA_real_,")
    b("                                     subject_prop_missing = NA_real_, excluded = TRUE)) %>%")
    b("  arrange(subject, trial)")
  }
  b("if (!nrow(d)) stop(\"All trials were excluded.\")")
  b("")

  b("# ---- 3. Interpolate and smooth ----")
  interp_only <- p$filter %in% c("lowpass", "none")
  b("# Once per sampling rate (hz sets the cubic max-gap length)",
    if (interp_only) "; interpolation only: a 1-sample moving average leaves values unchanged" else "")
  b("d <- bind_rows(lapply(split(d, d$.hz), function(di) {")
  b("  suppressMessages(gazer::smooth_interpolate_pupil(")
  b("    di, pupil = \"pupil\", extendpupil = \"extendpupil\", extendblinks = TRUE,")
  b("    step.first = ", lit(if (interp_only) "interp" else p$step_first),
    ", filter = ", lit(if (interp_only) "moving" else p$filter),
    ", maxgap = ", lit(p$maxgap), ",")
  b("    type = ", lit(p$interp_type), ", hz = di$.hz[1], n = ", lit(if (interp_only) 1 else p$ma_n), "))")
  b("}))")
  b("d <- arrange(as_tibble(d), subject, trial, time)")
  if (isTRUE(p$use_lowpass)) {
    b("")
    b("# Low-pass filter: zero-phase Butterworth, per trial (skipped if a trial")
    b("# still has missing values or is too short)")
    b("lp <- function(x, hz) {")
    b("  if (anyNA(x) || length(x) <= 3 * (", lit(p$lp_order), " + 1)) return(x)")
    b("  suppressMessages(gazer::lowpass_filter(x, order = ", lit(p$lp_order), ", filter_to_use = ",
      lit(p$lp_cutoff), ", samplerate = hz))")
    b("}")
    b("d <- d %>%")
    b("  group_by(subject, trial) %>%")
    b("  mutate(pup_interp = lp(pup_interp, .hz[1])) %>%")
    b("  ungroup()")
  }
  b("")

  b("# ---- 4. Baseline, re-scaling and time-locking ----")
  stat <- if (is.null(p$baseline_stat)) "median" else p$baseline_stat
  if (p$baseline == "event") {
    fns <- c(fns, "has_event")
    b("# Mark the first baseline event in each trial, so gazeR sees one per trial,")
    b("# then restore the messages")
    b("d <- d %>%")
    b("  group_by(subject, trial) %>%")
    b("  mutate(.orig_message = message,")
    b("         message = {")
    b("           h <- has_event(message, ", lit(p$baseline_event), ")")
    b("           ifelse(h & cumsum(h) == 1, \".BASELINE_EVENT\", NA_character_)")
    b("         }) %>%")
    b("  ungroup()")
    b("d <- suppressMessages(gazer::baseline_correction_pupil_msg(")
    b("  d, pupil_colname = \"pup_interp\", baseline_dur = ", lit(p$baseline_dur), ", event = \".BASELINE_EVENT\",")
    b("  baseline_method = ", lit(p$baseline_method), ", baseline_stat = ", lit(stat), "))")
    b("d$message <- d$.orig_message")
    b("d$.orig_message <- NULL")
    b("d$event_offset_time <- NULL")
  } else if (p$baseline == "window") {
    b("d <- suppressMessages(gazer::baseline_correction_pupil(")
    b("  d, pupil_colname = \"pup_interp\", baseline_window = ", lit(p$baseline_window), ",")
    b("  baseline_method = ", lit(p$baseline_method), ", baseline_stat = ", lit(stat), "))")
  } else {
    b("d$baselinecorrectedp <- d$pup_interp  # no baseline correction")
  }
  out_col <- output_column(p)
  if (out_col == "pup_z") {
    b("d <- gazer::zscore_pupil(d, pupil_col = \"baselinecorrectedp\", by = ", lit(p$zscore), ", new_col = \"pup_z\")")
  }
  timevar <- "time"
  if (isTRUE(p$timelock) && isTRUE(meta$has_message)) {
    fns <- c(fns, "event_onset")
    timevar <- "time_zero"
    b("# Time 0 = the first of these events in each trial; trials without one are dropped")
    b("d <- d %>%")
    b("  group_by(subject, trial) %>%")
    b("  mutate(time_zero = event_onset(time, message, ", lit(p$timelock_event), ")) %>%")
    b("  ungroup() %>%")
    b("  filter(!is.na(time_zero))")
    if (num(p$window[1])) b("d <- filter(d, time_zero >= ", lit(p$window[1]), ")")
    if (num(p$window[2])) b("d <- filter(d, time_zero <= ", lit(p$window[2]), ")")
  }
  b("names(d)[names(d) == \".hz\"] <- \"processing_hz\"")
  b("d[intersect(c(\"interp\", \"pup\", \"index\", \"movingavgpup\"), names(d))] <- NULL")

  # ---- Assemble ----
  out <- c(out, "# ---- Helpers from shiny gazeR (pipeline.R) ----------------------------", "")
  out <- c(out, paste0(script_helpers(unique(fns)), "\n"))
  out <- c(out, load)
  if (isTRUE(meta$eyes)) {
    add("# ---- Pre-processing, one eye at a time ------------------------------------")
    add("# Both eyes get the same settings and blink mask (blink in either eye); only")
    add("# trials that pass for both eyes are kept.")
    if (isTRUE(p$shared_missing)) {
      add("# A sample missing in one eye is set missing in the other too")
      add("gone <- is.na(d$pupil_left) | d$pupil_left <= 0 | is.na(d$pupil_right) | d$pupil_right <= 0")
      add("d$pupil_left[gone] <- NA")
      add("d$pupil_right[gone] <- NA")
    }
    add("preprocess <- function(d) {")
    out <- c(out, ifelse(nzchar(body), paste0("  ", body), ""))
    add("  list(data = d, quality = quality)")
    add("}")
    add("")
    add("one_eye <- function(d, side) {")
    add("  d$pupil <- d[[paste0(\"pupil_\", side)]]")
    add("  for (v in c(\"x\", \"y\")) if (paste0(v, \"_\", side) %in% names(d)) d[[v]] <- d[[paste0(v, \"_\", side)]]")
    add("  d[setdiff(names(d), c(\"pupil_left\", \"pupil_right\"))]")
    add("}")
    add("run_both <- function(d) lapply(c(left = \"left\", right = \"right\"), function(s) preprocess(one_eye(d, s)))")
    add("kept <- function(r) distinct(r$data, subject, trial)")
    add("")
    add("r <- run_both(d)")
    add("quality <- bind_rows(lapply(c(\"left\", \"right\"), function(s) mutate(r[[s]]$quality, eye = s)))")
    add("both <- inner_join(kept(r$left), kept(r$right), by = c(\"subject\", \"trial\"))")
    add("if (nrow(kept(r$left)) + nrow(kept(r$right)) > 2 * nrow(both)) {")
    add("  # Re-run both eyes on the trials that passed for both")
    add("  r <- run_both(semi_join(d, both, by = c(\"subject\", \"trial\")))")
    add("  both <- inner_join(kept(r$left), kept(r$right), by = c(\"subject\", \"trial\"))")
    add("}")
    add("processed <- bind_rows(lapply(c(\"left\", \"right\"), function(s) mutate(r[[s]]$data, eye = s))) %>%")
    add("  semi_join(both, by = c(\"subject\", \"trial\"))")
    aggvars <- unique(c(p$group_cols, "eye", "timebins"))
  } else {
    add("# ---- Pre-processing --------------------------------------------------------")
    out <- c(out, body)
    add("processed <- d")
    aggvars <- unique(c(p$group_cols, "timebins"))
  }
  add("")
  add("# ---- 5. Bin ----------------------------------------------------------------")
  add("binned <- gazer::downsample_gaze(processed, bin.length = ", lit(p$bin_length), ", timevar = ", lit(timevar), ",")
  add("                                 aggvars = ", lit(aggvars), ", type = \"pupil\", pupil = ", lit(out_col), ")")
  add("")
  add("# ---- Save -----------------------------------------------------------------")
  add("data.table::fwrite(processed, \"processed_samples.csv\", na = \"NA\")")
  add("data.table::fwrite(binned, \"binned.csv\", na = \"NA\")")
  add("data.table::fwrite(quality, \"trial_quality.csv\", na = \"NA\")")
  paste(out, collapse = "\n")
}
